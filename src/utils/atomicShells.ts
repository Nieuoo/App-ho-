// Fallback algorithm to calculate shells if Z is arbitrary
export function calculateShellsForZ(z: number): number[] {
  if (ATOMIC_SHELLS_DATA[z]) {
    return ATOMIC_SHELLS_DATA[z];
  }
  // Standard Bohr capacity fallback
  const capacities = [2, 8, 18, 32, 32, 18, 8];
  const shells: number[] = [];
  let remaining = z;
  for (let i = 0; i < capacities.length && remaining > 0; i++) {
    const take = Math.min(remaining, capacities[i]);
    shells.push(take);
    remaining -= take;
  }
  return shells;
}

export function getShellInfoList(z: number): ShellInfo[] {
  const shells = calculateShellsForZ(z);
  return shells.map((electrons, index) => {
    const shellNumber = index + 1;
    const maxCapacity = 2 * shellNumber * shellNumber;
    const isValence = index === shells.length - 1;
    return {
      shellNumber,
      shellLetter: SHELL_LETTERS[index] || `Shell-${shellNumber}`,
      electrons,
      maxCapacity,
      isValence,
    };
  });
}
